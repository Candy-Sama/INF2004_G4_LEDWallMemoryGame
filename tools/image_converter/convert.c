int _dowildcard = -1;
#define BRIGHTNESS_PERCENT 2

// Packs red, green and blue into one number
static inline uint32_t urgb_u32(uint8_t r, uint8_t g, uint8_t b) {
    return ((uint32_t)(r) << 8) | ((uint32_t)(g) << 16) | (uint32_t)(b);
}

// Convert one picture into 192 byte RGB file and write its embedded lines
int convert_image(const char *path, const char *outdir, FILE *s_file, FILE *h_file){
    //build the image name from the file name, for example images/heart.png
    const char *base = strrchr(path,'/');
    base = base ? base + 1 : path;
    char name[64];
    snprintf(name, sizeof(name), "%s", base);
    char *dot = strrchr(name,'.');
    if (dot) *dot = 0;

    // Convert png to array using stbi extension
    int width, height, channels;
    unsigned char *pixels = stbi_load(path, &width, &height, &channels, 3);
    if (pixels == NULL){
        fprintf(stderr, "load failed %s: %s\n", path, stbi_failure_reason());
        return 1;
    }
    fprintf(stderr, "loaded %s: %d x %d\n", name, width, height);

    // Shrink the picture to 8x8 and keep pixels sharp
    unsigned char small[8*8*3];
    unsigned char *result = stbir_resize(
        pixels, width, height, 0,
        small, 8, 8, 0,
        STBIR_RGB,
        STBIR_TYPE_UINT8,
        STBIR_EDGE_CLAMP,
        STBIR_FILTER_POINT_SAMPLE
    );
    stbi_image_free(pixels);
    if (result == NULL){
        fprintf(stderr, "resize failed %s\n", path);
        return 1;
    }

    // Scale the bright ness to 20 percent and store the RGB bytes
    unsigned char out[192];
    int lit = 0;
    for (int y = 0; y < 8; y++) {
        for (int x = 0; x < 8; x++) {
            int pos = (y * 8 + x) * 3;
            int red = small[pos];
            int green = small[pos + 1];
            int blue = small[pos + 2];

            // Scale to BRIGHTNESS_PERCENT
            red = red * BRIGHTNESS_PERCENT / 100;
            green = green * BRIGHTNESS_PERCENT / 100;
            blue = blue * BRIGHTNESS_PERCENT / 100;

            int index = y * 8 + x;
            out[index * 3] = red;
            out[index * 3 + 1] = green;
            out[index * 3 + 2] = blue;
            
            if (red || green || blue) {
                lit++;
            }
        }
    }
    fprintf(stderr, "lit LEDs: %d\n", lit);

    // Save the 192 byets as a .bin file
    char bin_path[256];
    snprintf(bin_path, sizeof(bin_path), "%s/images_bin/%s.bin", outdir, name);
    FILE *f =  fopen(bin_path, "wb");
    if (f == NULL){
        fprintf(stderr, "cannot write %s\n", bin_path);
        return 1;
    }
    fwrite(out, 1, sizeof(out), f);
    fclose(f);

    // Preview the picture in the terminal, # is a lit LED and . is a dark LED
    printf("\nImage Preview:\n");
    for (int y = 0; y < 8; y++) {
        for (int x = 0; x < 8; x++) {
            int pos = (y * 8 + x) * 3;
            // Uses the 8x8 RGB values before brightness dimming so it's clearly visible in console
            fprintf(stderr, "\033[48;2;%d;%d;%dm  \033[0m", small[pos], small[pos + 1], small[pos + 2]);
        }
        fprintf(stderr, "\n");
    }

    // Embed the .bin file into the firmware and declare it in the header
    fprintf(s_file, ".global %s_bin\n%s_bin:\n.incbin \"images_bin/%s.bin\"\n\n", name, name, name);
    fprintf(h_file, "extern const uint8_t %s_bin[192];\n", name);

    return 0;
    }

int main(int argc, char *argv[]){
    if(argc < 3){
        fprintf(stderr, "Usage: convert <output_dir> images/a.png images/b.png ...\n");
        return 1;
    }
    const char *outdir = argv[1];

    char s_path[256], h_path[256];
    snprintf(s_path, sizeof(s_path), "%s/imagedata_bin.S", outdir);
    snprintf(h_path, sizeof(h_path), "%s/imagedata.h", outdir);
    FILE *s_file = fopen(s_path, "w");
    FILE *h_file = fopen(h_path, "w");
    if (s_file == NULL || h_file == NULL){
        fprintf(stderr, "cannot open output files in %s\n", outdir);
        return 1;
    }

    fprintf(s_file, "/* Generated by convert.c. Do not edit by hand. */\n.section .rodata\n\n");
    fprintf(h_file, "/* Generated by convert.c. Do not edit by hand. */\n");
    fprintf(h_file, "#ifndef IMAGEDATA_H\n#define IMAGEDATA_H\n\n#include <stdint.h>\n\n");

    int failed = 0;
    for (int i = 2; i < argc; i++){
        if (convert_image(argv[i], outdir, s_file, h_file) != 0){
            failed++;
        }
    }

    fprintf(h_file, "\n#endif\n");
    fclose(s_file);
    fclose(h_file);

    if (failed > 0){
        fprintf(stderr, "%d picture(s) failed\n", failed);
        return 1;
    }
    return 0;
}
